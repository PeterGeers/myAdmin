/**
 * Responsive iframe-resize handshake — the HOSTED (child) side (spec 11 task 5.4; R5.2b / E4b,
 * design §10 "External iframe + resize").
 *
 * When the public application form is embedded via `<iframe>` in an external site (a Google Site,
 * the h-dcn portal), the parent document has no way to know the form's rendered height, so a
 * fixed-height iframe clips the form (notably inside a sandboxed Google Sites gadget). The fix is
 * the standard iframe-resize handshake:
 *
 *  - the HOSTED form (this module) measures its own content height and POSTs it to the parent via
 *    `window.parent.postMessage(...)` on mount and whenever the content height changes;
 *  - the EMBED snippet (generated by `applicationShellForm.buildIframeSnippet`) carries a tiny
 *    parent-side listener that validates the message and resizes the `<iframe>`.
 *
 * ## Security — a message is a message (CWE-346 / postMessage hygiene)
 *
 * A `postMessage` emitter and a listener are BOTH trust boundaries. This child side:
 *  - posts a STRUCTURED, type-tagged payload (`{ type, height }`) — never a bare number — so the
 *    parent listener can validate the shape and ignore the ocean of unrelated `postMessage`
 *    traffic (analytics, wallets, other widgets) that lands on a busy host page;
 *  - targets a caller-supplied parent origin when known, falling back to `'*'` ONLY for the height
 *    signal, which carries no secret (it is a layout integer). The message is non-sensitive by
 *    design, so a `'*'` target leaks nothing; the SCOPING that matters is on the PARENT listener,
 *    which validates `event.origin` against the embedding allow-list (the snippet side).
 *
 * The emit is a no-op when the form is NOT framed (`window.parent === window`), so a standalone /
 * same-origin render never posts to itself.
 */

/**
 * The stable message `type` token identifying a height signal from the hosted application form.
 * The parent listener keys on this EXACT string + the `source` namespace so it ignores every other
 * `postMessage` on the host page. Changing it is a breaking change to the embed contract.
 */
export const IFRAME_RESIZE_MESSAGE_TYPE = 'myadmin:application-form:height' as const;

/** A `source` tag so a strict listener can double-check the message provenance namespace. */
export const IFRAME_RESIZE_SOURCE = 'myadmin-application-form' as const;

/** The structured height message the hosted form posts to its parent. */
export interface IframeResizeMessage {
  type: typeof IFRAME_RESIZE_MESSAGE_TYPE;
  source: typeof IFRAME_RESIZE_SOURCE;
  /** The measured content height in CSS pixels (a non-negative integer). */
  height: number;
}

/**
 * Build the structured height message. Kept pure (no DOM, no `window`) so it is trivially testable
 * and so both the emit path and tests share ONE shape. A non-finite / negative height is clamped
 * to 0 (never emit garbage the parent would turn into a broken layout).
 */
export function buildResizeMessage(height: number): IframeResizeMessage {
  const h = Number.isFinite(height) && height > 0 ? Math.ceil(height) : 0;
  return { type: IFRAME_RESIZE_MESSAGE_TYPE, source: IFRAME_RESIZE_SOURCE, height: h };
}

/** Narrow unknown data to a well-formed {@link IframeResizeMessage} (used by the parent listener). */
export function isResizeMessage(data: unknown): data is IframeResizeMessage {
  if (!data || typeof data !== 'object') return false;
  const m = data as Record<string, unknown>;
  return (
    m.type === IFRAME_RESIZE_MESSAGE_TYPE &&
    m.source === IFRAME_RESIZE_SOURCE &&
    typeof m.height === 'number' &&
    Number.isFinite(m.height) &&
    m.height >= 0
  );
}

/**
 * Whether the current document is being rendered inside an iframe (a different window owns the
 * frame). A same-window render (standalone `<slug>.jabaki.nl/apply`, or the in-app preview) returns
 * false, so {@link postHeightToParent} is a no-op there.
 */
export function isFramed(win: Window = window): boolean {
  try {
    return win.parent != null && win.parent !== win;
  } catch {
    // A cross-origin parent can throw on access in some engines — if we cannot read it, we ARE
    // framed cross-origin, which is exactly the case we post for.
    return true;
  }
}

/**
 * Measure the document's rendered content height. Uses the larger of the scroll/offset metrics so
 * a form taller than the viewport reports its FULL height (the parent then grows the iframe to fit,
 * removing the inner scrollbar). Returns 0 when there is no document (SSR / tests without a DOM).
 */
export function measureDocumentHeight(doc: Document = document): number {
  const body = doc.body;
  const html = doc.documentElement;
  if (!body && !html) return 0;
  return Math.max(
    body?.scrollHeight ?? 0,
    body?.offsetHeight ?? 0,
    html?.clientHeight ?? 0,
    html?.scrollHeight ?? 0,
    html?.offsetHeight ?? 0,
  );
}

/**
 * Post the current content height to the parent frame — the child side of the handshake. A no-op
 * when the form is not framed (standalone / in-app preview), so it never posts to itself.
 *
 * `targetOrigin` SHOULD be the embedding parent's origin when known; it falls back to `'*'` because
 * the height is a non-sensitive layout integer (see the module header) and the hosted form does not
 * generally know which allow-listed origin framed it. The authoritative origin check lives on the
 * PARENT listener (the snippet), which rejects any message whose `event.origin` is not the hosted
 * form's own origin.
 */
export function postHeightToParent(
  height: number,
  options: { win?: Window; targetOrigin?: string } = {},
): void {
  const win = options.win ?? window;
  if (!isFramed(win)) return;
  const message = buildResizeMessage(height);
  try {
    win.parent.postMessage(message, options.targetOrigin ?? '*');
  } catch {
    // A locked-down parent can reject the post — swallow so the form never throws on a resize.
  }
}
